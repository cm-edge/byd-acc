"""Dataset adapters for detection generation (UA-DETRAC, UAVDT).

Each adapter knows, for its dataset:
  - how to list video names,
  - where the image frames for a video live,
  - the glob pattern for frame images,
  - the train/test split of a video,
  - where the per-video detection .txt should be written.

These are generation-only; GT loading / evaluation lives in the scoring scripts.
Output paths and file naming match the existing reference detection files so
downstream scripts pick them up unchanged.

MOT17 is intentionally not handled here — it is generated by
scoring/compute_mot17_detections.py.
"""

from pathlib import Path
from typing import List, Optional


class DatasetAdapter:
    def get_video_split(self, video_name: str) -> str:
        raise NotImplementedError

    def get_frame_dir(self, video_name: str, data_root: Path) -> Path:
        raise NotImplementedError

    def get_frame_glob(self) -> str:
        return "img*.jpg"

    def list_videos(self, data_root: Path, split: Optional[str] = None) -> List[str]:
        raise NotImplementedError

    def get_output_file(self, model_folder: str, video_name: str,
                        data_root: Path) -> Path:
        """Return the .txt path to write for this model + video."""
        raise NotImplementedError


# ---------------------------------------------------------------------------
# UA-DETRAC
# ---------------------------------------------------------------------------
class UADETRACAdapter(DatasetAdapter):
    """UA-DETRAC: 960x540, DETRAC-{Train,Test}-Detections layout.

    Expected data_root::

        data_root/
            DETRAC-Images/MVI_xxxxx/img00001.jpg ...
            DETRAC-Detections/DETRAC-{Train,Test}-Detections/{MODEL}/
                MVI_xxxxx_Det_{MODEL}.txt   (written here)
    """

    # Exact train video IDs (rest are test).
    TRAIN_IDS = {
        20011, 20012, 20032, 20033, 20034, 20035, 20051, 20052,
        20061, 20062, 20063, 20064, 20065,
        39761, 39771, 39781, 39801, 39811, 39821, 39851, 39861, 39931,
        40131, 40141, 40152, 40161, 40162, 40171, 40172, 40181, 40191,
        40192, 40201, 40204, 40211, 40212, 40213, 40241, 40243, 40244,
        40732, 40751, 40752, 40871, 40962, 40963, 40981, 40991, 40992,
        41063, 41073,
        63521, 63525, 63544, 63552, 63553, 63554, 63561, 63562, 63563,
    }

    def get_video_split(self, video_name: str) -> str:
        return "train" if int(video_name.split("_")[1]) in self.TRAIN_IDS else "test"

    def get_frame_dir(self, video_name: str, data_root: Path) -> Path:
        return data_root / "DETRAC-Images" / video_name

    def get_frame_glob(self) -> str:
        return "img*.jpg"

    def list_videos(self, data_root: Path, split: Optional[str] = None) -> List[str]:
        images_dir = data_root / "DETRAC-Images"
        if not images_dir.exists():
            return []
        videos = sorted(d.name for d in images_dir.iterdir() if d.is_dir())
        if split:
            videos = [v for v in videos if self.get_video_split(v) == split]
        return videos

    def get_output_file(self, model_folder: str, video_name: str,
                        data_root: Path) -> Path:
        split = self.get_video_split(video_name)
        return (
            data_root / "DETRAC-Detections"
            / f"DETRAC-{split.capitalize()}-Detections"
            / model_folder / f"{video_name}_Det_{model_folder}.txt"
        )


# ---------------------------------------------------------------------------
# UAVDT
# ---------------------------------------------------------------------------
class UAVDTAdapter(DatasetAdapter):
    """UAVDT: 1080x540, UAV-benchmark layout, flat Detections/{MODEL}/.

    Expected data_root::

        data_root/
            UAV-benchmark-M/M0101/img000001.jpg ...
            Detections/{MODEL}/M0101_Det_{MODEL}.txt   (written here)

    UAVDT has no standard detection train/test split; all videos report "train".
    """

    def get_video_split(self, video_name: str) -> str:
        return "train"

    def get_frame_dir(self, video_name: str, data_root: Path) -> Path:
        return data_root / "UAV-benchmark-M" / video_name

    def get_frame_glob(self) -> str:
        return "img*.jpg"

    def list_videos(self, data_root: Path, split: Optional[str] = None) -> List[str]:
        images_dir = data_root / "UAV-benchmark-M"
        if not images_dir.exists():
            return []
        return sorted(d.name for d in images_dir.iterdir() if d.is_dir())

    def get_output_file(self, model_folder: str, video_name: str,
                        data_root: Path) -> Path:
        return data_root / "Detections" / model_folder / f"{video_name}_Det_{model_folder}.txt"


# ---------------------------------------------------------------------------
# Registry
# ---------------------------------------------------------------------------
_ADAPTERS = {
    "ua-detrac": UADETRACAdapter,
    "uavdt":     UAVDTAdapter,
}

DATASET_NAMES = list(_ADAPTERS)

# Default dataset roots relative to the repo root (parent of this package).
DEFAULT_DATA_ROOT = {
    "ua-detrac": "data/UA-DETRAC",
    "uavdt":     "data/UAVDT",
}


def get_adapter(dataset_name: str) -> DatasetAdapter:
    key = dataset_name.lower()
    if key not in _ADAPTERS:
        raise ValueError(
            f"Unknown dataset '{dataset_name}'. Choose from: {DATASET_NAMES}"
        )
    return _ADAPTERS[key]()
