# ---------------------------------------------------------------------------
# Per-dataset COCO class filter (1-based COCO ids)
# ---------------------------------------------------------------------------
# COCO ids: 3=car, 4=motorcycle, 6=bus, 8=truck.
#
# UA-DETRAC keeps {3,4,6,8} (car/moto/bus/truck) to match the existing reference
# detection files, which contain all four classes. (Real UA-DETRAC GT is only
# car/bus, so moto/truck become FP downstream — but the paper's numbers were
# computed on exactly these detections, so we reproduce them faithfully.)
#
# UAVDT keeps {3,6,8} (car/bus/truck, NO motorcycle) to match its reference
# files, which contain no motorcycle detections.
DATASET_CLASS_FILTER = {
    "ua-detrac": {3, 4, 6, 8},
    "uavdt":     {3, 6, 8},
}

