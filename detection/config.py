"""Detection configuration for in-repo regeneration of weak/strong detections.

This module backs `run_detection.py`, which regenerates the UA-DETRAC and UAVDT
detection .txt files used downstream by the PTC / XGBoost / derived scoring
scripts. The goal is a self-contained pipeline: instead of shipping the (large)
precomputed detection files, a user downloads the public datasets and runs the
detector here. The parameters below are pinned to reproduce the detections the
paper's numbers were computed on.

Pinned reproduction parameters (do NOT change without re-validating downstream):
  - weak   = fasterrcnn_mobilenet_v3_large_fpn  (FULL-res, min_size=800/max=1333).
             NOTE: the output folder is labelled "...320-FPN" for historical
             compatibility, but the actual model is the full-res FPN variant.
             The literal `_320_fpn` model (min 320/max 640) downscales frames and
             badly weakens detections — see compute_mot17_detections.py for the
             same trap on MOT17.
  - strong = fasterrcnn_resnet50_fpn_v2
  - transform = weights.transforms()  (no manual resize)
  - conf      = 0.0  (save all; torchvision internally floors at box_score_thresh
                      ~0.05). Downstream scripts apply their own thresholds.
  - per-dataset class filter (see DATASET_CLASS_FILTER below).

MOT17 detections are generated by a separate script
(scoring/compute_mot17_detections.py) and are intentionally not handled here.
"""

