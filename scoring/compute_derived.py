#!/usr/bin/env python3
"""
Compute per-frame weak_map and strong_map for each test video.

UA-DETRAC / UAVDT:
  Reads pre-computed detection .txt files; computes AP at IoU=0.7 per frame
  against dataset ground truth using per-frame independent evaluation.

MOT17:
  Reads per-frame XML detections (generated by compute_mot17_detections.py) and MOT17 GT.
  Evaluates with GLOBAL AP (all predictions pooled across all frames of a
  sequence, then one precision-recall curve computed). Also emits per-frame AP for oracle/fig6 use.

Output:
    scores/derived/{dataset}/{video}.csv
      columns: frame_id, weak_map, strong_map

These files are required by reproduce/tab2.py, fig5.py, fig6.py.

Usage:
    python scoring/compute_derived.py
    python scoring/compute_derived.py --datasets ua-detrac uavdt mot17
    python scoring/compute_derived.py --split test   # default
"""

