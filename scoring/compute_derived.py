MODEL_STRONG     = "FASTERRCNN-RESNET50-FPN-V2"
CONF_THR     = 0.1
IOF_THR      = 0.5
IOU_THRESH   = 0.7

SPLITS_FILE  = ROOT / "dataset" / "video_splits.json"
SCORES_BASE  = ROOT / "scores" / "derived"

