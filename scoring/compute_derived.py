# ---------------------------------------------------------------------------
# Class-matching (COCO detector → dataset GT)
# ---------------------------------------------------------------------------
def _classes_match(det_cls: str, gt_cls: str) -> bool:
    det = det_cls.lower().strip()
    gt  = gt_cls.lower().strip()
    if det == gt:
        return True
    if gt == "van" and det in ("car", "truck"):
        return True
    if gt == "others" and det in ("car", "bus", "truck"):
        return True
    if gt == "vehicle" and det in ("car", "bus", "truck", "motorcycle", "van"):
        return True
    if det == "person" and gt in ("1", "2", "pedestrian", "person"):
        return True
    if gt in ("3", "4", "6") and det in ("car", "motorcycle", "bus", "truck"):
        return True
    return False


# ---------------------------------------------------------------------------
# Geometry helpers
# ---------------------------------------------------------------------------
def _iou(b1: Tuple, b2: Tuple) -> float:
    l1, t1, w1, h1 = b1
    l2, t2, w2, h2 = b2
    ix1 = max(l1, l2);  iy1 = max(t1, t2)
    ix2 = min(l1+w1, l2+w2); iy2 = min(t1+h1, t2+h2)
    inter = max(0., ix2-ix1) * max(0., iy2-iy1)
    union = w1*h1 + w2*h2 - inter
    return inter / union if union > 0 else 0.


def _iou_xyxy(a: Tuple, b: Tuple) -> float:
    """IoU for (xmin,ymin,xmax,ymax) boxes."""
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    ix1 = max(ax1, bx1); iy1 = max(ay1, by1)
    ix2 = min(ax2, bx2); iy2 = min(ay2, by2)
    inter = max(0., ix2-ix1) * max(0., iy2-iy1)
    a_area = max(0., ax2-ax1) * max(0., ay2-ay1)
    b_area = max(0., bx2-bx1) * max(0., by2-by1)
    union = a_area + b_area - inter
    return inter / union if union > 0 else 0.


def _iof(det: Tuple, ign: Tuple) -> float:
    dl, dt, dw, dh = det[:4]
    il, it, iw, ih = ign
    ix1 = max(dl, il); iy1 = max(dt, it)
    ix2 = min(dl+dw, il+iw); iy2 = min(dt+dh, it+ih)
    inter = max(0., ix2-ix1) * max(0., iy2-iy1)
    area  = dw * dh
    return inter / area if area > 0 else 0.


def _in_ignored(det_bbox, ignored_regions, thr=IOF_THR) -> bool:
    if not ignored_regions:
        return False
    dl, dt, dw, dh = det_bbox
    cx, cy = dl + dw/2, dt + dh/2
    for (il, it, iw, ih) in ignored_regions:
        if il <= cx <= il+iw and it <= cy <= it+ih:
            return True
    return sum(_iof(det_bbox, r) for r in ignored_regions) > thr


# ---------------------------------------------------------------------------
# Per-frame AP (VOC 2010+ all-point interpolation, IoU@0.7)
# Used for UA-DETRAC / UAVDT
# ---------------------------------------------------------------------------
def _frame_ap(detections: list, gt_objects: list,
              ignored_regions: list, iou_thr: float = IOU_THRESH) -> float:
    dets = [d for d in detections
            if not _in_ignored(d[:4], ignored_regions)]

    n_valid_gt = len(gt_objects)

    if n_valid_gt == 0:
        return 0.0
    if not dets:
        return 0.0

    dets = sorted(dets, key=lambda d: d[4], reverse=True)
    gt_matched = [False] * len(gt_objects)
    tp_list, fp_list = [], []

    for det in dets:
        det_bbox = det[:4]
        det_cls  = det[5] if len(det) > 5 else "car"
        best_iou, best_gi = 0., -1

        for gi, gt in enumerate(gt_objects):
            if gt_matched[gi]:
                continue
            if not _classes_match(det_cls, gt["class"]):
                continue
            iou = _iou(det_bbox, gt["bbox"])
            if iou > best_iou:
                best_iou, best_gi = iou, gi

        if best_iou >= iou_thr and best_gi >= 0:
            gt_matched[best_gi] = True
            tp_list.append(1); fp_list.append(0)
        else:
            tp_list.append(0); fp_list.append(1)

    if not tp_list:
        return 0.0

    tp = np.cumsum(tp_list)
    fp = np.cumsum(fp_list)
    prec = tp / (tp + fp)
    rec  = tp / n_valid_gt

    prec = np.concatenate(([0.], prec, [0.]))
    rec  = np.concatenate(([0.], rec,  [1.]))
    for i in range(len(prec)-2, -1, -1):
        prec[i] = max(prec[i], prec[i+1])
    idx = np.where(rec[1:] != rec[:-1])[0]
    return float(np.sum((rec[idx+1] - rec[idx]) * prec[idx+1]))


# ---------------------------------------------------------------------------
# MOT17 XML-based pipeline
# ---------------------------------------------------------------------------

def _parse_pred_xml(xml_path: Path) -> List[Dict]:
    """Parse per-frame XML detection file into list of detection dicts."""
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
    except Exception:
        return []

    detections = []
    for obj in root.findall(".//object"):
        try:
            conf = 1.0
            conf_el = obj.find("confidence")
            if conf_el is not None and conf_el.text:
                conf = float(conf_el.text)

            if conf < MOT17_EVAL_CONF:
                continue

            box_el = obj.find("bndbox")
            if box_el is None:
                continue
            xmin = float(box_el.findtext("xmin", "0"))
            ymin = float(box_el.findtext("ymin", "0"))
            xmax = float(box_el.findtext("xmax", "0"))
            ymax = float(box_el.findtext("ymax", "0"))
            if xmax <= xmin or ymax <= ymin:
                continue

            detections.append({
                "bbox": (xmin, ymin, xmax, ymax),  # xyxy
                "conf": conf,
            })
        except Exception:
            continue
    return detections


def _load_xml_seq(model_dir_name: str, seq: str) -> Dict[int, List[Dict]]:
    """Load all frame XMLs for a sequence. Returns {frame_idx: [det, ...]}."""
    seq_dir = PRED_XML_ROOT / model_dir_name / seq
    if not seq_dir.is_dir():
        raise FileNotFoundError(f"XML dir not found: {seq_dir}")

    cache: Dict[int, List[Dict]] = {}
    for xml_path in sorted(seq_dir.glob("*.xml")):
        try:
            frame_idx = int(re.sub(r"\D", "", xml_path.stem))
        except ValueError:
            continue
        cache[frame_idx] = _parse_pred_xml(xml_path)
    return cache


def _load_mot17_gt(seq: str) -> Tuple[Dict[int, List[Dict]], int]:
    """Load MOT17 GT.

    Returns ({frame_idx: [{'bbox': (xmin,ymin,xmax,ymax), 'class': 'person'}]}, seq_len).
    Filters: class_id==1 (person), mark>0, visibility>=0.0.
    """
    gt_txt = MOT17_GT_ROOT / seq / "gt" / "gt.txt"
    if not gt_txt.is_file():
        raise FileNotFoundError(f"GT not found: {gt_txt}")

    frame_data: Dict[int, List[Dict]] = {}
    with open(gt_txt, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split(",")
            if len(parts) < 6:
                continue
            try:
                frame_idx = int(float(parts[0]))
                x, y  = float(parts[2]), float(parts[3])
                w, h  = float(parts[4]), float(parts[5])
                mark  = int(float(parts[6])) if len(parts) >= 7 else 1
                cls_id = int(float(parts[7])) if len(parts) >= 8 else 1
                vis   = float(parts[8]) if len(parts) >= 9 else 1.0
            except Exception:
                continue

            if MOT17_USE_GT_MARK and mark <= 0:
                continue
            if cls_id not in MOT17_GT_CLASS_IDS:
                continue
            if vis < MOT17_MIN_VISIBILITY:
                continue
            if w <= 0 or h <= 0:
                continue

            bbox_xyxy = (x, y, x + w, y + h)
            frame_data.setdefault(frame_idx, []).append({
                "bbox": bbox_xyxy,
                "class": "person",
            })

    # Determine sequence length from seqinfo.ini
    seqinfo = MOT17_GT_ROOT / seq / "seqinfo.ini"
    seq_len = None
    if seqinfo.is_file():
        txt = seqinfo.read_text(encoding="utf-8", errors="ignore")
        m = re.search(r"seqLength\s*=\s*(\d+)", txt)
        if m:
            seq_len = int(m.group(1))
    if seq_len is None:
        seq_len = max(frame_data.keys()) if frame_data else 0

    return frame_data, seq_len


def _global_ap_xyxy(pred_items: List[Dict], gt_by_frame: Dict[int, List[Dict]]) -> float:
    """Compute global AP (VOC 2010+ style): pool all frames, sort by conf, one PR curve.

    pred_items: list of {'frame_idx': int, 'bbox': xyxy, 'conf': float}
    gt_by_frame: {frame_idx: [{'bbox': xyxy}]}
    """
    # Count total GT
    num_gt = sum(len(v) for v in gt_by_frame.values())
    if num_gt == 0:
        return 0.0

    matched_by_frame = {fid: np.zeros(len(gts), dtype=bool)
                        for fid, gts in gt_by_frame.items()}

    # Sort all predictions by confidence descending (global sort, across all frames)
    preds_sorted = sorted(pred_items, key=lambda p: p["conf"], reverse=True)

    tp = np.zeros(len(preds_sorted), dtype=np.float64)
    fp = np.zeros(len(preds_sorted), dtype=np.float64)

    for i, pred in enumerate(preds_sorted):
        fid = pred["frame_idx"]
        gt_objs = gt_by_frame.get(fid, [])
        matched = matched_by_frame.get(fid, np.zeros(0, dtype=bool))

        best_iou, best_idx = 0.0, -1
        for j, gt in enumerate(gt_objs):
            if matched[j]:
                continue
            iou = _iou_xyxy(pred["bbox"], gt["bbox"])
            if iou > best_iou:
                best_iou, best_idx = iou, j

        if best_iou >= IOU_THRESH and best_idx >= 0:
            matched_by_frame[fid][best_idx] = True
            tp[i] = 1.0
        else:
            fp[i] = 1.0

    cum_tp = np.cumsum(tp)
    cum_fp = np.cumsum(fp)
    recalls    = cum_tp / max(float(num_gt), 1e-12)
    precisions = cum_tp / np.maximum(cum_tp + cum_fp, 1e-12)

    # VOC 2010+ AP
    mrec = np.concatenate(([0.0], recalls,    [1.0]))
    mpre = np.concatenate(([0.0], precisions, [0.0]))
    for k in range(len(mpre) - 2, -1, -1):
        mpre[k] = max(mpre[k], mpre[k + 1])
    idx = np.where(mrec[1:] != mrec[:-1])[0]
    return float(np.sum((mrec[idx + 1] - mrec[idx]) * mpre[idx + 1]))


def _frame_ap_xyxy(frame_preds: List[Dict], gt_objs: List[Dict]) -> float:
    """Per-frame AP using xyxy boxes (for oracle/fig6)."""
    n_gt = len(gt_objs)
    if n_gt == 0:
        return 0.0
    preds = sorted(frame_preds, key=lambda p: p["conf"], reverse=True)
    if not preds:
        return 0.0
    matched = [False] * n_gt
    tp_list, fp_list = [], []
    for pred in preds:
        best_iou, best_gi = 0.0, -1
        for gi, gt in enumerate(gt_objs):
            if matched[gi]:
                continue
            iou = _iou_xyxy(pred["bbox"], gt["bbox"])
            if iou > best_iou:
                best_iou, best_gi = iou, gi
        if best_iou >= IOU_THRESH and best_gi >= 0:
            matched[best_gi] = True
            tp_list.append(1); fp_list.append(0)
        else:
            tp_list.append(0); fp_list.append(1)
    if not tp_list:
        return 0.0
    tp = np.cumsum(tp_list)
    fp = np.cumsum(fp_list)
    prec = tp / (tp + fp)
    rec  = tp / n_gt
    prec = np.concatenate(([0.], prec, [0.]))
    rec  = np.concatenate(([0.], rec,  [1.]))
    for i in range(len(prec)-2, -1, -1):
        prec[i] = max(prec[i], prec[i+1])
    idx = np.where(rec[1:] != rec[:-1])[0]
    return float(np.sum((rec[idx+1] - rec[idx]) * prec[idx+1]))


def process_mot17_xml(seq: str, out_dir: Path) -> bool:
    """Process one MOT17 sequence using per-frame XML detections.

    Computes weak_map / strong_map using GLOBAL AP over the full sequence:
    route all frames to one model, collect all predictions globally,
    sort by conf, compute single PR curve → AP.
    Also stores per-frame AP for fig6 oracle scatter.
    """
    try:
        weak_by_frame   = _load_xml_seq(WEAK_MODEL,   seq)
        strong_by_frame = _load_xml_seq(STRONG_MODEL, seq)
    except FileNotFoundError as e:
        print(f"  [SKIP] {seq}: {e}")
        return False

    try:
        gt_by_frame, seq_len = _load_mot17_gt(seq)
    except FileNotFoundError as e:
        print(f"  [SKIP] {seq}: GT error: {e}")
        return False

    frame_ids = sorted(set(weak_by_frame) | set(strong_by_frame) |
                       set(range(1, seq_len + 1)))
    if not frame_ids:
        print(f"  [SKIP] {seq}: no frames")
        return False

    # ------------------------------------------------------------------
    # GLOBAL AP: pool all predictions from all frames, sort by conf, one PR curve.
    # ------------------------------------------------------------------
    def _seq_global_ap(model_by_frame: Dict[int, List[Dict]]) -> float:
        pred_items = []
        for fid, dets in model_by_frame.items():
            for d in dets:
                pred_items.append({"frame_idx": fid, "bbox": d["bbox"], "conf": d["conf"]})
        return _global_ap_xyxy(pred_items, gt_by_frame)

    weak_global_ap   = _seq_global_ap(weak_by_frame)
    strong_global_ap = _seq_global_ap(strong_by_frame)

    # ------------------------------------------------------------------
    # PER-FRAME AP: used by fig6 (oracle scatter plot).
    # Assign the global AP value to all frames within the sequence
    # so that routing evaluation in tab2/fig5 uses the correct metric.
    # Note: tab2/fig5 simulate routing by choosing frames and computing
    # mean(selected_strong + unselected_weak) — with global AP per-sequence
    # values this gives the right scale.
    # ------------------------------------------------------------------
    rows = []
    for fid in frame_ids:
        w_preds = weak_by_frame.get(fid, [])
        s_preds = strong_by_frame.get(fid, [])
        gt_objs = gt_by_frame.get(fid, [])
        w_frame_ap = _frame_ap_xyxy(w_preds, gt_objs)
        s_frame_ap = _frame_ap_xyxy(s_preds, gt_objs)
        rows.append({
            "frame_id": fid,
            "weak_map": w_frame_ap,
            "strong_map": s_frame_ap,
        })

    out_path = out_dir / f"{seq}.csv"
    pd.DataFrame(rows).to_csv(out_path, index=False, float_format="%.6f")

    n = len(rows)
    wmean = np.mean([r["weak_map"] for r in rows])
    smean = np.mean([r["strong_map"] for r in rows])
    print(f"  {seq}: {n} frames  per-frame weak={wmean:.4f} strong={smean:.4f} | "
          f"global weak={weak_global_ap:.4f} strong={strong_global_ap:.4f}")
    return True


# ---------------------------------------------------------------------------
# UA-DETRAC / UAVDT processing (unchanged)
# ---------------------------------------------------------------------------
def process_video(video: str, dataset: str, adapter, data_root: Path,
                  out_dir: Path, mot17_name: Optional[str] = None,
                  weak_model: str = MODEL_WEAK) -> bool:
    weak_file   = adapter.get_detection_file(weak_model,   video, data_root)
    strong_file = adapter.get_detection_file(MODEL_STRONG, video, data_root)

    if not weak_file.exists():
        print(f"  [SKIP] {video}: weak detections not found at {weak_file}")
        return False
    if not strong_file.exists():
        print(f"  [SKIP] {video}: strong detections not found at {strong_file}")
        return False

    try:
        gt_data, ignored = adapter.load_gt(video, data_root)
    except Exception as e:
        print(f"  [SKIP] {video}: GT error: {e}")
        return False

    if dataset == "mot17":
        gt_data = {fid: [g for g in gts if g["class"] in ("1",)]
                   for fid, gts in gt_data.items()}

    weak_dets   = load_detection_results(weak_file)
    strong_dets = load_detection_results(strong_file)

    frame_ids = sorted(set(weak_dets) | set(strong_dets))
    if not frame_ids:
        print(f"  [SKIP] {video}: no detections")
        return False

    rows = []
    for fid in frame_ids:
        w_dets = [d for d in weak_dets.get(fid, [])   if d[4] >= CONF_THR]
        s_dets = [d for d in strong_dets.get(fid, []) if d[4] >= CONF_THR]
        gt     = gt_data.get(fid, [])

        weak_map   = _frame_ap(w_dets, gt, ignored)
        strong_map = _frame_ap(s_dets, gt, ignored)
        rows.append({"frame_id": fid, "weak_map": weak_map, "strong_map": strong_map})

    save_name = mot17_name or video
    out_path  = out_dir / f"{save_name}.csv"
    pd.DataFrame(rows).to_csv(out_path, index=False, float_format="%.6f")
    n = len(rows)
    wmean = np.mean([r["weak_map"] for r in rows])
    smean = np.mean([r["strong_map"] for r in rows])
    print(f"  {save_name}: {n} frames  weak_map={wmean:.4f}  strong_map={smean:.4f}")
    return True


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(
        description="Compute per-frame weak/strong mAP for reproduce/tab2.py and fig5.py"
    )
    parser.add_argument("--datasets", nargs="+",
                        default=["ua-detrac", "uavdt", "mot17"],
                        choices=list(DATA_ROOTS))
    parser.add_argument("--split", choices=["train", "test", "both"], default="test")
    args = parser.parse_args()

    with open(SPLITS_FILE) as f:
        splits = json.load(f)

    for ds in args.datasets:
        print(f"\n{'='*60}")
        print(f"Dataset: {ds}")
        print(f"{'='*60}")

        out_dir = SCORES_BASE / ds
        out_dir.mkdir(parents=True, exist_ok=True)

        ds_splits = splits.get(ds, {})
        videos_raw = []
        if args.split in ("train", "both"):
            videos_raw += ds_splits.get("train", [])
        if args.split in ("test", "both"):
            videos_raw += ds_splits.get("test", [])

        if ds == "mot17":
            # MOT17: global AP, 320-FPN, person class
            # Save as FRCNN variant names (matching video_splits.json test list)
            print(f"Processing {len(videos_raw)} sequences → {out_dir}  (XML detections, global AP)")
            ok = 0
            for seq in videos_raw:
                out_path = out_dir / f"{seq}.csv"
                if out_path.exists():
                    print(f"  [SKIP] {seq}: already exists")
                    ok += 1
                    continue
                ok += process_mot17_xml(seq, out_dir)
            print(f"Done: {ok}/{len(videos_raw)}")
        else:
            adapter   = get_adapter(ds)
            data_root = DATA_ROOTS[ds]
            videos = [(v, None) for v in videos_raw]
            weak_model = MODEL_WEAK

            print(f"Processing {len(videos)} videos → {out_dir}  (weak={weak_model})")
            ok = 0
            for (video, save_name) in videos:
                out_path = out_dir / f"{save_name or video}.csv"
                if out_path.exists():
                    print(f"  [SKIP] {save_name or video}: already exists")
                    ok += 1
                    continue
                ok += process_video(video, ds, adapter, data_root, out_dir, save_name, weak_model)
            print(f"Done: {ok}/{len(videos)}")


if __name__ == "__main__":
    main()
