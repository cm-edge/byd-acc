#!/usr/bin/env python3
"""
Compute MOT17 routing curves and pairwise accuracy (Table 2, Fig 5).

Key difference from UA-DETRAC/UAVDT:
  - MOT17 uses GLOBAL AP: all predictions pooled across all frames of the val set,
    then one precision-recall curve computed. NOT mean of per-frame APs.
  - Detection input: per-frame XML files generated by compute_mot17_detections.py
  - Score files: scores/iounet/, scores/gfl/, scores/ptc/, scores/xgboost/

Output:
  scores/mot17_routing_curves.csv
    columns: method, offload_ratio, mAP
  scores/mot17_routing_pairwise.csv
    columns: method, pairwise_acc, og20

Usage:
    python scoring/compute_mot17_routing.py
    python scoring/compute_mot17_routing.py --budgets 0 0.1 0.2 0.3 0.5 1.0
"""

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "dataset"))

SPLITS_FILE = ROOT / "dataset" / "video_splits.json"
SCORES_DIR  = ROOT / "scores"

PRED_XML_ROOT = ROOT / "data" / "mot17" / "pred_xml" / "TRAIN"
MOT17_GT_ROOT = ROOT / "data" / "mot17" / "train"

WEAK_MODEL   = "fasterrcnn_mobilenet_v3_large_320_fpn"
STRONG_MODEL = "fasterrcnn_resnet50_fpn_v2"

EVAL_CONF      = 0.1
IOU_THR        = 0.7
GT_CLASS_IDS   = {1}
MIN_VISIBILITY = 0.0
USE_GT_MARK    = True
RANDOM_SEED    = 42

# Budgets: 0..100% in steps of 10 (matches paper's curves_mot17.csv offload_ratio column)
DEFAULT_BUDGETS = [i / 100.0 for i in range(0, 101, 10)]

# Score columns and routing direction (strong_select)
# "lowest" = low score → route to strong (invert=True in tab2.py terms)
# "highest" = high score → route to strong
SCORE_CFG = {
    "IoU-Net": {
        # conf-weighted mean is the routing column used by the reference MOT17
        # pipeline and reported in the paper (Tab 2). Falls back to iou_net_mean
        # for older score CSVs that lack the column.
        "dir": "iounet", "col": "iou_net_conf_weighted_mean", "strong_select": "lowest"
    },
    "GFL": {
        # gfl_final_score (= conf * quality) per-frame mean; the reference routing col.
        "dir": "gfl",     "col": "gfl_final_score_mean",       "strong_select": "lowest"
    },
    "PTC-IoU": {
        "dir": "ptc",     "col": "ptc_h",          "strong_select": "lowest"
    },
    "XGBoost": {
        "dir": "xgboost", "col": "predicted_gain", "strong_select": "highest"
    },
}

VAL_SEQS = ["MOT17-02-FRCNN", "MOT17-11-FRCNN", "MOT17-13-FRCNN"]


# ---------------------------------------------------------------------------
# IoU helpers
# ---------------------------------------------------------------------------
def _iou_xyxy(a: Tuple, b: Tuple) -> float:
    ax1, ay1, ax2, ay2 = a
    bx1, by1, bx2, by2 = b
    ix1 = max(ax1, bx1); iy1 = max(ay1, by1)
    ix2 = min(ax2, bx2); iy2 = min(ay2, by2)
    inter = max(0., ix2-ix1) * max(0., iy2-iy1)
    a_area = max(0., ax2-ax1) * max(0., ay2-ay1)
    b_area = max(0., bx2-bx1) * max(0., by2-by1)
    union = a_area + b_area - inter
    return inter / union if union > 0 else 0.


# ---------------------------------------------------------------------------
# XML parsing
# ---------------------------------------------------------------------------
def _parse_pred_xml(xml_path: Path) -> List[Dict]:
    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()
    except Exception:
        return []

    detections = []
    for obj in root.findall(".//object"):
        try:
            conf = 1.0
            conf_el = obj.find("confidence")
            if conf_el is not None and conf_el.text:
                conf = float(conf_el.text)
            if conf < EVAL_CONF:
                continue
            box_el = obj.find("bndbox")
            if box_el is None:
                continue
            xmin = float(box_el.findtext("xmin", "0"))
            ymin = float(box_el.findtext("ymin", "0"))
            xmax = float(box_el.findtext("xmax", "0"))
            ymax = float(box_el.findtext("ymax", "0"))
            if xmax <= xmin or ymax <= ymin:
                continue
            detections.append({"bbox": (xmin, ymin, xmax, ymax), "conf": conf})
        except Exception:
            continue
    return detections


def _load_xml_seq(model_name: str, seq: str) -> Dict[int, List[Dict]]:
    seq_dir = PRED_XML_ROOT / model_name / seq
    if not seq_dir.is_dir():
        raise FileNotFoundError(f"XML dir not found: {seq_dir}")
    cache: Dict[int, List[Dict]] = {}
    for xml_path in sorted(seq_dir.glob("*.xml")):
        try:
            fid = int(re.sub(r"\D", "", xml_path.stem))
        except ValueError:
            continue
        cache[fid] = _parse_pred_xml(xml_path)
    return cache


# ---------------------------------------------------------------------------
# GT parsing
# ---------------------------------------------------------------------------
def _load_mot17_gt(seq: str) -> Tuple[Dict[int, List[Dict]], int]:
    gt_txt = MOT17_GT_ROOT / seq / "gt" / "gt.txt"
    if not gt_txt.is_file():
        raise FileNotFoundError(f"GT not found: {gt_txt}")

    frame_data: Dict[int, List[Dict]] = {}
    with open(gt_txt, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            parts = line.split(",")
            if len(parts) < 6:
                continue
            try:
                fid   = int(float(parts[0]))
                x, y  = float(parts[2]), float(parts[3])
                w, h  = float(parts[4]), float(parts[5])
                mark  = int(float(parts[6])) if len(parts) >= 7 else 1
                cls_id = int(float(parts[7])) if len(parts) >= 8 else 1
                vis   = float(parts[8]) if len(parts) >= 9 else 1.0
            except Exception:
                continue
            if USE_GT_MARK and mark <= 0:
                continue
            if cls_id not in GT_CLASS_IDS:
                continue
            if vis < MIN_VISIBILITY:
                continue
            if w <= 0 or h <= 0:
                continue
            frame_data.setdefault(fid, []).append({
                "bbox": (x, y, x + w, y + h),  # xyxy
            })

    seqinfo = MOT17_GT_ROOT / seq / "seqinfo.ini"
    seq_len = None
    if seqinfo.is_file():
        txt = seqinfo.read_text(encoding="utf-8", errors="ignore")
        m = re.search(r"seqLength\s*=\s*(\d+)", txt)
        if m:
            seq_len = int(m.group(1))
    if seq_len is None:
        seq_len = max(frame_data.keys()) if frame_data else 0
    return frame_data, seq_len


# ---------------------------------------------------------------------------
# Global AP
# ---------------------------------------------------------------------------
def _global_ap(pred_items: List[Dict], gt_by_frame: Dict[int, List[Dict]]) -> float:
    """
    pred_items: [{'frame_idx': int, 'bbox': xyxy, 'conf': float}]
    gt_by_frame: {frame_idx: [{'bbox': xyxy}]}

    Pools all predictions across all frames, sorts by conf globally,
    then computes one precision-recall curve → AP (VOC 2010+ style).
    """
    num_gt = sum(len(v) for v in gt_by_frame.values())
    if num_gt == 0:
        return 0.0
    if not pred_items:
        return 0.0

    matched = {fid: np.zeros(len(gts), dtype=bool)
               for fid, gts in gt_by_frame.items()}

    preds_sorted = sorted(pred_items, key=lambda p: p["conf"], reverse=True)
    tp = np.zeros(len(preds_sorted), dtype=np.float64)
    fp = np.zeros(len(preds_sorted), dtype=np.float64)

    for i, pred in enumerate(preds_sorted):
        fid = pred["frame_idx"]
        gt_objs = gt_by_frame.get(fid, [])
        mat = matched.get(fid, np.zeros(0, dtype=bool))
        best_iou, best_idx = 0.0, -1
        for j, gt in enumerate(gt_objs):
            if mat[j]:
                continue
            iou = _iou_xyxy(pred["bbox"], gt["bbox"])
            if iou > best_iou:
                best_iou, best_idx = iou, j
        if best_iou >= IOU_THR and best_idx >= 0:
            matched[fid][best_idx] = True
            tp[i] = 1.0
        else:
            fp[i] = 1.0

    cum_tp = np.cumsum(tp)
    cum_fp = np.cumsum(fp)
    recalls    = cum_tp / max(float(num_gt), 1e-12)
    precisions = cum_tp / np.maximum(cum_tp + cum_fp, 1e-12)

    mrec = np.concatenate(([0.0], recalls,    [1.0]))
    mpre = np.concatenate(([0.0], precisions, [0.0]))
    for k in range(len(mpre) - 2, -1, -1):
        mpre[k] = max(mpre[k], mpre[k + 1])
    idx = np.where(mrec[1:] != mrec[:-1])[0]
    return float(np.sum((mrec[idx + 1] - mrec[idx]) * mpre[idx + 1]))


def _frame_ap(frame_preds: List[Dict], gt_objs: List[Dict]) -> float:
    """Per-frame AP for oracle computation (fig6 oracle_ap_frame_gain)."""
    n_gt = len(gt_objs)
    if n_gt == 0:
        return 0.0
    preds = sorted(frame_preds, key=lambda p: p["conf"], reverse=True)
    if not preds:
        return 0.0
    matched = [False] * n_gt
    tp_list, fp_list = [], []
    for pred in preds:
        best_iou, best_gi = 0.0, -1
        for gi, gt in enumerate(gt_objs):
            if matched[gi]:
                continue
            iou = _iou_xyxy(pred["bbox"], gt["bbox"])
            if iou > best_iou:
                best_iou, best_gi = iou, gi
        if best_iou >= IOU_THR and best_gi >= 0:
            matched[best_gi] = True
            tp_list.append(1); fp_list.append(0)
        else:
            tp_list.append(0); fp_list.append(1)
    if not tp_list:
        return 0.0
    tp = np.cumsum(tp_list)
    fp = np.cumsum(fp_list)
    prec = tp / (tp + fp)
    rec  = tp / n_gt
    prec = np.concatenate(([0.], prec, [0.]))
    rec  = np.concatenate(([0.], rec,  [1.]))
    for i in range(len(prec)-2, -1, -1):
        prec[i] = max(prec[i], prec[i+1])
    idx = np.where(rec[1:] != rec[:-1])[0]
    return float(np.sum((rec[idx+1] - rec[idx]) * prec[idx+1]))


# ---------------------------------------------------------------------------
# Load frame list and per-frame scores
# ---------------------------------------------------------------------------
def _build_frame_df(seqs: List[str],
                    weak_cache: Dict[Tuple[str, int], List[Dict]],
                    seq_lens: Dict[str, int]) -> pd.DataFrame:
    """Build a DataFrame with one row per frame across all val sequences."""
    rows = []
    for seq in seqs:
        seq_key = seq.lower()
        slen = seq_lens.get(seq, 0)
        for fid in range(1, slen + 1):
            rows.append({"seq": seq, "seq_key": seq_key, "frame_idx": fid})
    return pd.DataFrame(rows)


# Fallback columns if the preferred routing column is absent (older CSVs).
_COL_FALLBACK = {
    "iou_net_conf_weighted_mean": "iou_net_mean",
    "gfl_final_score_mean":       "gfl_mean",
}


def _load_score_file(method_cfg: Dict, seq: str) -> Optional[pd.Series]:
    score_dir = SCORES_DIR / method_cfg["dir"] / "mot17"
    col = method_cfg["col"]
    path = score_dir / f"{seq}.csv"
    if not path.exists():
        return None
    df = pd.read_csv(path)
    if col not in df.columns:
        col = _COL_FALLBACK.get(col)
        if col is None or col not in df.columns:
            return None
    df = df.set_index("frame_id")
    return df[col]


# ---------------------------------------------------------------------------
# Routing evaluation
# ---------------------------------------------------------------------------
def _simulate_routing(
    frame_df: pd.DataFrame,
    score_series: Dict[str, Optional[pd.Series]],
    strong_select: str,
    budget: float,
    all_gt: Dict[Tuple[str, int], List[Dict]],
    weak_cache: Dict[Tuple[str, int], List[Dict]],
    strong_cache: Dict[Tuple[str, int], List[Dict]],
) -> float:
    """Route frames to weak/strong based on scores, evaluate with global AP."""
    n = len(frame_df)
    k = max(1, int(round(budget * n))) if budget > 0 else 0
    if budget >= 1.0:
        k = n

    # Build score vector
    scores = np.full(n, np.nan)
    for i, row in enumerate(frame_df.itertuples()):
        s = score_series.get(row.seq)
        if s is not None and row.frame_idx in s.index:
            scores[i] = float(s.loc[row.frame_idx])

    # Fill NaN: for low-is-best (lowest→strong), fill with max (won't be selected)
    # for high-is-best (highest→strong), fill with min
    nan_mask = np.isnan(scores)
    if nan_mask.any():
        fill = float(np.nanmax(scores)) if strong_select == "lowest" else float(np.nanmin(scores))
        scores[nan_mask] = fill if not np.isnan(fill) else 0.0

    # Select top-k frames to strong model
    if k <= 0:
        strong_mask = np.zeros(n, dtype=bool)
    elif k >= n:
        strong_mask = np.ones(n, dtype=bool)
    else:
        if strong_select == "lowest":
            order = np.argsort(scores, kind="stable")
        else:
            order = np.argsort(-scores, kind="stable")
        strong_mask = np.zeros(n, dtype=bool)
        strong_mask[order[:k]] = True

    # Collect predictions
    pred_items = []
    gt_by_frame: Dict[int, List[Dict]] = {}

    for i, row in enumerate(frame_df.itertuples()):
        key = (row.seq_key, row.frame_idx)
        cache = strong_cache if strong_mask[i] else weak_cache
        for d in cache.get(key, []):
            pred_items.append({
                "frame_idx": row.frame_idx,
                "_key": key,
                "bbox": d["bbox"],
                "conf": d["conf"],
            })

    # GT is the same regardless of routing
    gt_merged: Dict[Tuple[str, int], List[Dict]] = {}
    for i, row in enumerate(frame_df.itertuples()):
        key = (row.seq_key, row.frame_idx)
        if key not in gt_merged:
            gt_merged[key] = all_gt.get(key, [])

    # Global AP using per-key (video, frame) matching
    return _global_ap_keyed(pred_items, gt_merged)


def _global_ap_keyed(
    pred_items: List[Dict],
    gt_by_key: Dict[Tuple[str, int], List[Dict]],
) -> float:
    """Global AP where GT is keyed by (seq_key, frame_idx)."""
    num_gt = sum(len(v) for v in gt_by_key.values())
    if num_gt == 0:
        return 0.0
    if not pred_items:
        return 0.0

    matched = {k: np.zeros(len(gts), dtype=bool) for k, gts in gt_by_key.items()}
    preds_sorted = sorted(pred_items, key=lambda p: p["conf"], reverse=True)
    tp = np.zeros(len(preds_sorted), dtype=np.float64)
    fp = np.zeros(len(preds_sorted), dtype=np.float64)

    for i, pred in enumerate(preds_sorted):
        key = pred["_key"]
        gt_objs = gt_by_key.get(key, [])
        mat = matched.get(key, np.zeros(0, dtype=bool))
        best_iou, best_idx = 0.0, -1
        for j, gt in enumerate(gt_objs):
            if mat[j]:
                continue
            iou = _iou_xyxy(pred["bbox"], gt["bbox"])
            if iou > best_iou:
                best_iou, best_idx = iou, j
        if best_iou >= IOU_THR and best_idx >= 0:
            matched[key][best_idx] = True
            tp[i] = 1.0
        else:
            fp[i] = 1.0

    cum_tp = np.cumsum(tp)
    cum_fp = np.cumsum(fp)
    recalls    = cum_tp / max(float(num_gt), 1e-12)
    precisions = cum_tp / np.maximum(cum_tp + cum_fp, 1e-12)

    mrec = np.concatenate(([0.0], recalls,    [1.0]))
    mpre = np.concatenate(([0.0], precisions, [0.0]))
    for k in range(len(mpre) - 2, -1, -1):
        mpre[k] = max(mpre[k], mpre[k + 1])
    idx = np.where(mrec[1:] != mrec[:-1])[0]
    return float(np.sum((mrec[idx + 1] - mrec[idx]) * mpre[idx + 1]))


def _pairwise_acc(scores: np.ndarray, gains: np.ndarray,
                  max_pairs: int = 300_000, seed: int = RANDOM_SEED) -> float:
    """Pairwise accuracy: fraction of sampled pairs where score ordering matches gain ordering."""
    rng = np.random.default_rng(seed)
    n = len(scores)
    if n < 2:
        return float("nan")
    idx_i = rng.integers(0, n, size=max_pairs)
    idx_j = rng.integers(0, n, size=max_pairs)
    mask = idx_i != idx_j
    idx_i, idx_j = idx_i[mask], idx_j[mask]

    dt = gains[idx_i] - gains[idx_j]
    ds = scores[idx_i] - scores[idx_j]
    valid = np.abs(dt) > 1e-9
    if not valid.sum():
        return float("nan")
    dt, ds = dt[valid], ds[valid]
    tie_s = np.abs(ds) < 1e-9
    concordant = (np.sign(dt) == np.sign(ds)) & ~tie_s
    acc = (concordant.sum() + 0.5 * tie_s.sum()) / len(dt)
    return float(acc)


# ---------------------------------------------------------------------------
# Oracle frame scores (for fig6 and OG@20% computation)
# ---------------------------------------------------------------------------
def _build_oracle_frame_scores(
    seqs: List[str],
    all_gt: Dict[Tuple[str, int], List[Dict]],
    weak_cache: Dict[Tuple[str, int], List[Dict]],
    strong_cache: Dict[Tuple[str, int], List[Dict]],
    seq_lens: Dict[str, int],
) -> pd.DataFrame:
    rows = []
    for seq in seqs:
        seq_key = seq.lower()
        slen = seq_lens.get(seq, 0)
        for fid in range(1, slen + 1):
            key = (seq_key, fid)
            gt_objs = all_gt.get(key, [])
            w_ap = _frame_ap(weak_cache.get(key, []), gt_objs)
            s_ap = _frame_ap(strong_cache.get(key, []), gt_objs)
            rows.append({
                "seq": seq,
                "frame_idx": fid,
                "weak_ap_frame":  w_ap,
                "strong_ap_frame": s_ap,
                "oracle_ap_frame_gain": s_ap - w_ap,
            })
    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="MOT17 global-AP routing curves")
    parser.add_argument("--budgets", nargs="+", type=float, default=DEFAULT_BUDGETS)
    parser.add_argument("--seqs", nargs="+", default=VAL_SEQS)
    args = parser.parse_args()

    seqs = args.seqs

    print("Loading GT...")
    all_gt: Dict[Tuple[str, int], List[Dict]] = {}
    seq_lens: Dict[str, int] = {}
    for seq in seqs:
        gt_by_frame, slen = _load_mot17_gt(seq)
        seq_lens[seq] = slen
        seq_key = seq.lower()
        for fid, objs in gt_by_frame.items():
            all_gt[(seq_key, fid)] = objs
        # Include frames with 0 GT
        for fid in range(1, slen + 1):
            if (seq_key, fid) not in all_gt:
                all_gt[(seq_key, fid)] = []
    print(f"  GT frames: {len(all_gt)}")

    print("Loading weak XML cache...")
    weak_cache: Dict[Tuple[str, int], List[Dict]] = {}
    for seq in seqs:
        cache = _load_xml_seq(WEAK_MODEL, seq)
        seq_key = seq.lower()
        for fid, dets in cache.items():
            weak_cache[(seq_key, fid)] = dets
    print(f"  Weak frames: {len(weak_cache)}")

    print("Loading strong XML cache...")
    strong_cache: Dict[Tuple[str, int], List[Dict]] = {}
    for seq in seqs:
        cache = _load_xml_seq(STRONG_MODEL, seq)
        seq_key = seq.lower()
        for fid, dets in cache.items():
            strong_cache[(seq_key, fid)] = dets
    print(f"  Strong frames: {len(strong_cache)}")

    # Build frame DataFrame
    frame_rows = []
    for seq in seqs:
        seq_key = seq.lower()
        for fid in range(1, seq_lens[seq] + 1):
            frame_rows.append({"seq": seq, "seq_key": seq_key, "frame_idx": fid})
    frame_df = pd.DataFrame(frame_rows)
    n_frames = len(frame_df)
    print(f"  Total frames: {n_frames}")

    # Compute oracle frame scores (for oracle curve + fig6 + pairwise)
    print("\nComputing oracle frame scores...")
    oracle_df = _build_oracle_frame_scores(seqs, all_gt, weak_cache, strong_cache, seq_lens)

    # Weak/Strong global AP (at budget 0.0 and 1.0)
    weak_pred = []
    strong_pred = []
    for seq in seqs:
        seq_key = seq.lower()
        for fid in range(1, seq_lens[seq] + 1):
            key = (seq_key, fid)
            for d in weak_cache.get(key, []):
                weak_pred.append({"_key": key, "bbox": d["bbox"], "conf": d["conf"]})
            for d in strong_cache.get(key, []):
                strong_pred.append({"_key": key, "bbox": d["bbox"], "conf": d["conf"]})

    weak_ap   = _global_ap_keyed(weak_pred,   {k: all_gt[k] for k in all_gt})
    strong_ap = _global_ap_keyed(strong_pred, {k: all_gt[k] for k in all_gt})
    print(f"  Weak global AP:   {weak_ap:.6f}  (paper: 0.253468)")
    print(f"  Strong global AP: {strong_ap:.6f}  (paper: 0.379336)")

    # Oracle curve: route frames with highest gain first
    oracle_df_sorted = oracle_df.sort_values("oracle_ap_frame_gain", ascending=False)
    oracle_curve = {}
    for budget in args.budgets:
        k = max(1, int(round(budget * n_frames))) if budget > 0 else 0
        if budget >= 1.0:
            k = n_frames
        strong_keys = set()
        for i, row in enumerate(oracle_df_sorted.itertuples()):
            if i >= k:
                break
            strong_keys.add((row.seq.lower(), row.frame_idx))
        pred_items = []
        for seq in seqs:
            seq_key = seq.lower()
            for fid in range(1, seq_lens[seq] + 1):
                key = (seq_key, fid)
                cache = strong_cache if key in strong_keys else weak_cache
                for d in cache.get(key, []):
                    pred_items.append({"_key": key, "bbox": d["bbox"], "conf": d["conf"]})
        oracle_curve[budget] = _global_ap_keyed(pred_items, {k: all_gt[k] for k in all_gt})

    # Random curve: each budget gets its own seed to avoid correlation across budgets
    random_curve = {}
    for budget in args.budgets:
        k = max(1, int(round(budget * n_frames))) if budget > 0 else 0
        if budget >= 1.0:
            k = n_frames
        rng_b = np.random.default_rng(RANDOM_SEED + int(round(budget * 1000)))
        all_idx = np.arange(n_frames)
        chosen = set(rng_b.choice(all_idx, size=k, replace=False).tolist()) if k > 0 else set()
        pred_items = []
        for i, row in enumerate(frame_df.itertuples()):
            key = (row.seq_key, row.frame_idx)
            cache = strong_cache if i in chosen else weak_cache
            for d in cache.get(key, []):
                pred_items.append({"_key": key, "bbox": d["bbox"], "conf": d["conf"]})
        random_curve[budget] = _global_ap_keyed(pred_items, {k: all_gt[k] for k in all_gt})

    # Per-method routing curves and pairwise accuracy
    curve_rows = []
    pairwise_rows = []

    # Pure weak / pure strong / random / oracle baselines
    for budget in args.budgets:
        b_pct = int(round(budget * 100))
        curve_rows.append({"method": "weak",   "offload_ratio": b_pct, "mAP": weak_ap})
        curve_rows.append({"method": "strong",  "offload_ratio": b_pct, "mAP": strong_ap})
        curve_rows.append({"method": "Random",  "offload_ratio": b_pct, "mAP": random_curve.get(budget, float("nan"))})
        curve_rows.append({"method": "Oracle",  "offload_ratio": b_pct, "mAP": oracle_curve.get(budget, float("nan"))})

    # Oracle curve at 20% for OG@20% denominator
    oracle_at_20 = oracle_curve.get(0.2, float("nan"))

    for method, cfg in SCORE_CFG.items():
        print(f"\nMethod: {method}")
        # Load scores for all seqs
        score_series = {}
        for seq in seqs:
            s = _load_score_file(cfg, seq)
            score_series[seq] = s

        # Routing curves
        method_curve = {}
        for budget in args.budgets:
            ap = _simulate_routing(
                frame_df, score_series, cfg["strong_select"], budget,
                all_gt, weak_cache, strong_cache,
            )
            b_pct = int(round(budget * 100))
            curve_rows.append({"method": method, "offload_ratio": b_pct, "mAP": ap})
            method_curve[budget] = ap
            if b_pct == 30:
                print(f"  ρ=0.3 → mAP={ap:.6f}  (paper: see Tab 2)")

        # Pairwise accuracy (against oracle_ap_frame_gain)
        # Build aligned score + gain arrays
        sc_arr, gain_arr = [], []
        for seq in seqs:
            seq_key = seq.lower()
            s = score_series.get(seq)
            if s is None:
                continue
            sub = oracle_df[oracle_df["seq"] == seq]
            for row in sub.itertuples():
                if row.frame_idx in s.index:
                    raw_score = float(s.loc[row.frame_idx])
                    # For routing: invert so that "high score = route to strong"
                    score_for_routing = -raw_score if cfg["strong_select"] == "lowest" else raw_score
                    sc_arr.append(score_for_routing)
                    gain_arr.append(row.oracle_ap_frame_gain)
        if sc_arr:
            pw = _pairwise_acc(np.array(sc_arr), np.array(gain_arr))
            print(f"  pairwise_acc={pw:.4f}")
        else:
            pw = float("nan")

        # OG@20%
        ap_at_20 = method_curve.get(0.2, float("nan"))
        og20 = (ap_at_20 - weak_ap) / (oracle_at_20 - weak_ap) * 100.0 \
               if (oracle_at_20 - weak_ap) > 1e-9 else float("nan")
        print(f"  OG@20%={og20:.2f}%")

        pairwise_rows.append({
            "method": method,
            "pairwise_acc": pw,
            "og20": og20,
        })

    # Save curves
    curves_df = pd.DataFrame(curve_rows)
    # Pivot to wide format: offload_ratio as rows, methods as columns
    curves_wide = curves_df.pivot_table(
        index="offload_ratio", columns="method", values="mAP", aggfunc="first"
    ).reset_index()
    curves_wide.columns.name = None
    # Rename baseline columns to lowercase for consistency
    rename_map = {"Oracle": "oracle", "Random": "random", "weak": "weak", "strong": "strong"}
    curves_wide.rename(columns=rename_map, inplace=True)
    # Reorder columns to match paper_comparison format
    col_order = ["offload_ratio", "oracle", "random", "weak", "strong",
                 "IoU-Net", "GFL", "PTC-IoU", "XGBoost"]
    col_order = [c for c in col_order if c in curves_wide.columns]
    curves_wide = curves_wide[col_order]

    out_curves = SCORES_DIR / "mot17_routing_curves.csv"
    curves_wide.to_csv(out_curves, index=False, float_format="%.6f")
    print(f"\nSaved: {out_curves}")

    # Save pairwise
    pw_df = pd.DataFrame(pairwise_rows)
    out_pw = SCORES_DIR / "mot17_routing_pairwise.csv"
    pw_df.to_csv(out_pw, index=False, float_format="%.6f")
    print(f"Saved: {out_pw}")

    # Save oracle frame scores for fig6
    out_oracle = SCORES_DIR / "mot17_oracle_frame_scores.csv"
    oracle_df.to_csv(out_oracle, index=False, float_format="%.10f")
    print(f"Saved: {out_oracle}")

    print("\nDone.")
    print(f"Weak={weak_ap:.6f}  Strong={strong_ap:.6f}")


if __name__ == "__main__":
    main()
