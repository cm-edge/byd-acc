#!/usr/bin/env python3
"""
Compute PTC-IoU scores for all videos across datasets.

PTC-IoU is self-supervised — no ground-truth labels needed beyond optional
ignored-region filtering. Reads pre-computed weak-model detection .txt files
and writes per-video CSVs with columns [frame_id, ptc_det, ptc_loc, ptc_h].

MOT17: reads per-frame XML detections (generated by compute_mot17_detections.py)
for the 320-FPN model instead of .txt detection files.

Output layout:
    scores/ptc/{dataset}/{video}.csv

Supported datasets: ua-detrac, uavdt, mot17
Training is on UA-DETRAC only; PTC-IoU has no learned parameters.

Usage:
    python scoring/compute_ptc.py
    python scoring/compute_ptc.py --datasets uavdt mot17
    python scoring/compute_ptc.py --split train   # default: both
"""

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

SCRIPT_DIR = Path(__file__).parent.resolve()
PROJECT_ROOT = SCRIPT_DIR.parent
sys.path.insert(0, str(PROJECT_ROOT / "dataset"))

from adapters import get_adapter

MODEL_WEAK       = "FASTERRCNN-MOBILENET-V3-LARGE-FPN"        # UA-DETRAC/UAVDT
MODEL_WEAK_MOT17 = "FASTERRCNN-MOBILENET-V3-LARGE-320-FPN"   # MOT17 (has person class)
# Per-dataset confidence thresholds. Each dataset uses a different conf to match
# how its detections are filtered downstream: UA-DETRAC at 0.5, UAVDT and MOT17
# at 0.1.
CONF_THR       = 0.5  # UA-DETRAC
CONF_THR_UAVDT = 0.1  # UAVDT
CONF_THR_MOT17 = 0.1  # MOT17
IOU_THR    = 0.5
IOF_THR    = 0.5
SMOOTH_WIN = 9
DIOU_ALPHA = 0.7

# Dataset roots (download datasets into <repo>/data/; see detection/README.md).
DATA_ROOTS = {
    "ua-detrac": PROJECT_ROOT / "data" / "UA-DETRAC",
    "uavdt":     PROJECT_ROOT / "data" / "UAVDT",
    "mot17":     PROJECT_ROOT / "data" / "MOT17",
}

# Local MOT17 XML detection files (generated by compute_mot17_detections.py)
LOCAL_MOT17_XML_ROOT = PROJECT_ROOT / "data" / "mot17" / "pred_xml" / "TRAIN"
LOCAL_WEAK_MODEL     = "fasterrcnn_mobilenet_v3_large_320_fpn"

SCORES_BASE = PROJECT_ROOT / "scores" / "ptc"

# COCO vehicle class names in our detection files
VEHICLE_NAMES = {"car", "bus", "truck", "motorcycle", "van", "vehicle"}
# MOT17 person
PERSON_NAMES  = {"person"}


# ---------------------------------------------------------------------------
# Geometry helpers (copied from compute_ptc_scores.py)
# ---------------------------------------------------------------------------
Det = Tuple[float, float, float, float, float, str]
BBox = Tuple[float, float, float, float]


def _iou(b1: BBox, b2: BBox) -> float:
    x1, y1, w1, h1 = b1
    x2, y2, w2, h2 = b2
    ix1, iy1 = max(x1, x2), max(y1, y2)
    ix2, iy2 = min(x1+w1, x2+w2), min(y1+h1, y2+h2)
    inter = max(0., ix2-ix1) * max(0., iy2-iy1)
    union = w1*h1 + w2*h2 - inter
    return inter / union if union > 0 else 0.


def _iof(pred: BBox, ign: BBox) -> float:
    px, py, pw, ph = pred
    ix, iy, iw, ih = ign
    inter = max(0., min(px+pw, ix+iw)-max(px,ix)) * max(0., min(py+ph, iy+ih)-max(py,iy))
    area = max(0., pw) * max(0., ph)
    return inter / area if area > 0 else 0.


def _center(b: BBox): return b[0]+b[2]/2, b[1]+b[3]/2
def _from_center(cx, cy, w, h): return cx-w/2, cy-h/2, w, h


def _diou_like(b1: BBox, b2: BBox, alpha=DIOU_ALPHA) -> float:
    iou = _iou(b1, b2)
    cx1, cy1 = _center(b1)
    cx2, cy2 = _center(b2)
    d2 = (cx1-cx2)**2 + (cy1-cy2)**2
    ex1 = min(b1[0], b2[0]); ey1 = min(b1[1], b2[1])
    ex2 = max(b1[0]+b1[2], b2[0]+b2[2]); ey2 = max(b1[1]+b1[3], b2[1]+b2[3])
    c2 = (ex2-ex1)**2 + (ey2-ey1)**2 + 1e-12
    cs = float(np.exp(-d2 / c2))
    return float(np.clip(iou**alpha * cs**(1-alpha), 0., 1.))


def _predict_box(pp: BBox, p: BBox) -> BBox:
    cx_k, cy_k = _center(pp)
    cx_i, cy_i = _center(p)
    eps = 1e-12
    pw = float(np.exp(np.log(p[2]+eps)*2 - np.log(pp[2]+eps)))
    ph = float(np.exp(np.log(p[3]+eps)*2 - np.log(pp[3]+eps)))
    return _from_center(cx_i+(cx_i-cx_k), cy_i+(cy_i-cy_k), max(1e-6,pw), max(1e-6,ph))


def _build_iou_matrix(a, b):
    mat = np.zeros((len(a), len(b)), dtype=np.float32)
    for i, d1 in enumerate(a):
        for j, d2 in enumerate(b):
            if d1[5] == d2[5]:
                mat[i, j] = _iou(d1[:4], d2[:4])
    return mat


def _greedy_match(mat, thr):
    matches, tmp = [], mat.copy()
    while True:
        idx = np.unravel_index(np.argmax(tmp), tmp.shape)
        val = float(tmp[idx])
        if val < thr:
            break
        matches.append((int(idx[0]), int(idx[1]), val))
        tmp[idx[0], :] = -1; tmp[:, idx[1]] = -1
    return matches


def _centered_ma(x, k=SMOOTH_WIN):
    if k <= 1 or x.size == 0:
        return x.copy().astype(np.float32)
    y = np.empty_like(x, dtype=np.float32)
    half = k // 2
    for i in range(len(x)):
        y[i] = float(np.mean(x[max(0,i-half):min(len(x),i+half+1)]))
    return y


def _load_xml_detections_for_seq(seq: str, conf_thr: float) -> Dict[int, List]:
    """Load MOT17 detections from local XML files (generated by compute_mot17_detections.py).

    Returns {frame_idx: [(x, y, w, h, conf, 'person'), ...]} in xywh format,
    matching the format returned by load_detections() for .txt files.
    """
    seq_dir = LOCAL_MOT17_XML_ROOT / LOCAL_WEAK_MODEL / seq
    if not seq_dir.is_dir():
        raise FileNotFoundError(f"XML dir not found: {seq_dir}")

    result: Dict[int, List] = {}
    for xml_path in sorted(seq_dir.glob("*.xml")):
        try:
            fid = int(re.sub(r"\D", "", xml_path.stem))
        except ValueError:
            continue
        dets = []
        try:
            tree = ET.parse(xml_path)
            root = tree.getroot()
        except Exception:
            result[fid] = dets
            continue
        for obj in root.findall(".//object"):
            try:
                conf_el = obj.find("confidence")
                conf = float(conf_el.text) if conf_el is not None and conf_el.text else 1.0
                if conf < conf_thr:
                    continue
                box_el = obj.find("bndbox")
                if box_el is None:
                    continue
                xmin = float(box_el.findtext("xmin", "0"))
                ymin = float(box_el.findtext("ymin", "0"))
                xmax = float(box_el.findtext("xmax", "0"))
                ymax = float(box_el.findtext("ymax", "0"))
                if xmax <= xmin or ymax <= ymin:
                    continue
                # Convert xyxy → xywh to match load_detections() format
                dets.append((xmin, ymin, xmax - xmin, ymax - ymin, conf, "person"))
            except Exception:
                continue
        result[fid] = dets
    return result


def _ptc_det_raw(prev, curr) -> float:
    if not prev and not curr: return 1.
    if not prev or not curr:  return 0.
    matches = _greedy_match(_build_iou_matrix(prev, curr), IOU_THR)
    if not matches: return 0.
    ps = sum(float(d[4]) for d in prev)
    cs = sum(float(d[4]) for d in curr)
    matched = sum(min(float(prev[i][4]), float(curr[j][4])) for i,j,_ in matches)
    denom = ps + cs - matched
    return float(matched / denom) if denom > 0 else 0.


def _ptc_loc_raw(prev, curr, prevprev) -> float:
    if not prev and not curr: return 1.
    if not prev or not curr:  return 0.
    matches = _greedy_match(_build_iou_matrix(prev, curr), IOU_THR)
    if not matches: return 0.
    vals = []
    for pi, ci, match_iou in matches:
        if prevprev:
            bk = max(range(len(prevprev)),
                     key=lambda k: _iou(prevprev[k][:4], prev[pi][:4]),
                     default=None)
            if bk is not None and _iou(prevprev[bk][:4], prev[pi][:4]) > 0:
                pred = _predict_box(prevprev[bk][:4], prev[pi][:4])
                vals.append(_diou_like(pred, curr[ci][:4]))
                continue
        vals.append(float(match_iou))
    return float(np.mean(vals)) if vals else 0.


def _ptc_ass_raw(prev, curr) -> float:
    """Association stability: how unambiguous each correspondence is.

    For each current detection j, compute the margin between its best and
    second-best IoU against previous frame. High margin = unambiguous match.
    a_j = (s1 - s2) / (s1 + eps);  Ass = Σ conf_j * a_j / Σ conf_j
    """
    if not prev and not curr: return 1.
    if not prev or not curr:  return 0.
    eps = 1e-12
    weighted_sum = weight_sum = 0.
    for j, c in enumerate(curr):
        conf = float(c[4])
        # Compute IoU against all same-class previous dets (no class filter here
        # to match paper – we use raw IoU as in the HOTA decomposition spirit)
        ious = sorted(
            (_iou(p[:4], c[:4]) for p in prev if p[5] == c[5]),
            reverse=True
        )
        s1 = ious[0] if ious else 0.
        s2 = ious[1] if len(ious) >= 2 else 0.
        a_j = (s1 - s2) / (s1 + eps) if s1 > 0 else 0.
        weighted_sum += conf * a_j
        weight_sum   += conf
    return float(weighted_sum / weight_sum) if weight_sum > 0 else 0.


def compute_video_ptc(dets_by_frame, frame_ids, dataset: str = "ua-detrac") -> pd.DataFrame:
    T = len(frame_ids)
    raw_det = np.ones(T, dtype=np.float32)
    raw_ass = np.ones(T, dtype=np.float32)
    raw_loc = np.ones(T, dtype=np.float32)
    for t in range(1, T):
        prev     = dets_by_frame.get(frame_ids[t-1], [])
        curr     = dets_by_frame.get(frame_ids[t],   [])
        prevprev = dets_by_frame.get(frame_ids[t-2], []) if t >= 2 else []
        raw_det[t] = _ptc_det_raw(prev, curr)
        raw_ass[t] = _ptc_ass_raw(prev, curr)
        raw_loc[t] = _ptc_loc_raw(prev, curr, prevprev)
    ptc_det = np.clip(_centered_ma(raw_det), 0., 1.)
    ptc_ass = np.clip(_centered_ma(raw_ass), 0., 1.)
    ptc_loc = np.clip(_centered_ma(raw_loc), 0., 1.)

    # UA-DETRAC / UAVDT: geometric mean of det and loc (original formula, no ass term)
    #   ptc_h = sqrt(ptc_det * ptc_loc)
    # MOT17: grid-searched optimal (cfg_id=698): ptc_ass^1.0 * ptc_loc^0.15
    #   = ptc_ass * ptc_loc^0.15  (invert=True → low score means offload)
    if dataset == "mot17":
        ptc_h = np.clip(ptc_ass * (ptc_loc ** 0.15), 0., 1.)
    else:
        ptc_h = np.clip(np.sqrt(ptc_det * ptc_loc), 0., 1.)

    return pd.DataFrame({
        "frame_id": frame_ids,
        "ptc_det":  ptc_det.tolist(),
        "ptc_ass":  ptc_ass.tolist(),
        "ptc_loc":  ptc_loc.tolist(),
        "ptc_h":    ptc_h.tolist(),
    })


# ---------------------------------------------------------------------------
# Load detection file
# ---------------------------------------------------------------------------
def load_detections(det_file: Path, valid_classes: set, ignored: list,
                    conf_thr=CONF_THR) -> Dict[int, List[Det]]:
    # First pass: collect all frame IDs (even those where all dets fail filtering).
    # Frames with no valid dets are kept as empty lists so the temporal sequence
    # is correct for PTC smoothing.
    all_fids: Dict[int, List[Det]] = {}
    if not det_file.exists():
        return all_fids
    with open(det_file) as f:
        for line in f:
            parts = line.strip().split(",")
            if len(parts) < 7:
                continue
            try:
                fid  = int(parts[0])
                x, y, w, h = float(parts[2]), float(parts[3]), float(parts[4]), float(parts[5])
                conf = float(parts[6])
                cls  = parts[7].strip().lower() if len(parts) > 7 else "car"
            except (ValueError, IndexError):
                continue
            # Always register the frame (even if detection will be filtered out)
            if fid not in all_fids:
                all_fids[fid] = []
            if conf < conf_thr or cls not in valid_classes:
                continue
            if any(_iof((x,y,w,h), ig) > IOF_THR for ig in ignored):
                continue
            all_fids[fid].append((x, y, w, h, conf, cls))
    return all_fids


# ---------------------------------------------------------------------------
# Process one video (UA-DETRAC / UAVDT via .txt detection files)
# ---------------------------------------------------------------------------
def process_video(video: str, dataset: str, adapter, data_root: Path,
                  out_dir: Path, valid_classes: set, output_name: Optional[str] = None,
                  weak_model: str = MODEL_WEAK, conf_thr: float = CONF_THR) -> bool:
    det_file = adapter.get_detection_file(weak_model, video, data_root)
    if not det_file.exists():
        print(f"  [SKIP] {video}: no detection file at {det_file}")
        return False

    try:
        _, ignored = adapter.load_gt(video, data_root)
    except Exception:
        ignored = []

    dets = load_detections(det_file, valid_classes, ignored, conf_thr=conf_thr)
    if not any(v for v in dets.values()):
        print(f"  [SKIP] {video}: no valid detections after filtering")
        return False

    frame_ids = sorted(dets)
    df = compute_video_ptc(dets, frame_ids, dataset=dataset)

    save_name = output_name or video
    out_path = out_dir / f"{save_name}.csv"
    df.to_csv(out_path, index=False, float_format="%.6f")
    print(f"  {video}: {len(df)} frames  "
          f"ptc_det={df['ptc_det'].mean():.4f}  ptc_h={df['ptc_h'].mean():.4f}")
    return True


# ---------------------------------------------------------------------------
# Process one MOT17 sequence from local XML files
# ---------------------------------------------------------------------------
def process_mot17_xml(seq: str, out_dir: Path) -> bool:
    """Compute PTC-IoU for MOT17 from local XML detections.

    XML files must be generated first by compute_mot17_detections.py.
    Using the same detection stream as compute_mot17_routing.py ensures
    consistency. PTC formula: ptc_h = ptc_ass * ptc_loc^0.15 (cfg_id=698).
    """
    try:
        dets = _load_xml_detections_for_seq(seq, conf_thr=CONF_THR_MOT17)
    except FileNotFoundError as e:
        print(f"  [SKIP] {seq}: {e}")
        return False

    if not dets:
        print(f"  [SKIP] {seq}: no frames found in XML")
        return False

    frame_ids = sorted(dets)
    df = compute_video_ptc(dets, frame_ids, dataset="mot17")

    out_path = out_dir / f"{seq}.csv"
    df.to_csv(out_path, index=False, float_format="%.6f")
    print(f"  {seq}: {len(df)} frames  "
          f"ptc_det={df['ptc_det'].mean():.4f}  ptc_h={df['ptc_h'].mean():.4f}")
    return True


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    parser = argparse.ArgumentParser(description="Compute PTC-IoU scores across datasets")
    parser.add_argument("--datasets", nargs="+",
                        default=["ua-detrac", "uavdt", "mot17"],
                        choices=["ua-detrac", "uavdt", "mot17"])
    parser.add_argument("--splits-file", type=str,
                        default=str(PROJECT_ROOT / "dataset" / "video_splits.json"))
    parser.add_argument("--split", choices=["train", "test", "both"], default="both")
    parser.add_argument("--scores-dir", type=str, default=None,
                        help="Override output base dir (default: scores/ptc/)")
    args = parser.parse_args()

    with open(args.splits_file) as f:
        splits = json.load(f)

    base_out = Path(args.scores_dir) if args.scores_dir else SCORES_BASE

    for ds in args.datasets:
        if ds not in DATA_ROOTS:
            print(f"[SKIP] {ds}: not configured")
            continue
        print(f"\n{'='*60}")
        print(f"Dataset: {ds}")
        print(f"{'='*60}")

        out_dir = base_out / ds
        out_dir.mkdir(parents=True, exist_ok=True)

        ds_splits = splits.get(ds, {})
        videos_raw = []
        if args.split in ("train", "both"):
            videos_raw += ds_splits.get("train", [])
        if args.split in ("test", "both"):
            videos_raw += ds_splits.get("test", [])

        if ds == "mot17":
            # Compute PTC from local XML files (generated by compute_mot17_detections.py)
            print(f"Output: {out_dir}  (source: local XML from {LOCAL_MOT17_XML_ROOT})")
            print(f"Processing {len(videos_raw)} sequences...")
            ok = 0
            for seq in videos_raw:
                out_path = out_dir / f"{seq}.csv"
                if out_path.exists():
                    print(f"  [SKIP] {seq}: already exists")
                    ok += 1
                    continue
                ok += process_mot17_xml(seq, out_dir)
            print(f"Done: {ok}/{len(videos_raw)} sequences")
        else:
            adapter   = get_adapter(ds)
            data_root = DATA_ROOTS[ds]
            valid_classes = VEHICLE_NAMES

            videos_to_process = [(v, None) for v in videos_raw]
            weak_model = MODEL_WEAK
            conf_thr   = CONF_THR_UAVDT if ds == "uavdt" else CONF_THR
            print(f"Output: {out_dir}  (conf_thr={conf_thr})")
            print(f"Processing {len(videos_to_process)} videos...")

            ok = 0
            for (video, output_name) in videos_to_process:
                out_path = out_dir / f"{output_name or video}.csv"
                if out_path.exists():
                    print(f"  [SKIP] {output_name or video}: already exists")
                    ok += 1
                    continue
                ok += process_video(video, ds, adapter, data_root, out_dir,
                                    valid_classes, output_name, weak_model, conf_thr)
            print(f"Done: {ok}/{len(videos_to_process)} videos")


if __name__ == "__main__":
    main()
