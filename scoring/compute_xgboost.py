#!/usr/bin/env python3
"""
Derive XGBoost features and compute per-frame difficulty scores.

Reads pre-computed weak-model detection .txt files, derives a 30-feature
sliding-window representation, and regresses onto per-frame mAP gain
(∆mAP = strong_mAP − weak_mAP) using the trained XGBoost predictor.

Prerequisites:
  - Trained predictor in weights/xgboost/predictor.pkl
    (produced by training/train_xgboost.py)
  - Detection .txt files for both weak and strong models under data/

Output layout:
    scores/xgboost/{dataset}/{video}.csv
      columns: frame_id, predicted_gain

Usage:
    python scoring/compute_xgboost.py
    python scoring/compute_xgboost.py --datasets uavdt mot17
    python scoring/compute_xgboost.py --window 7
"""

import argparse
import json
import sys
from collections import deque
from pathlib import Path
from typing import List

import numpy as np
import pandas as pd

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "estimator"))
sys.path.insert(0, str(ROOT / "dataset"))

from feature_extractor import FrameFeatureExtractor, build_window_vector
from predictor import DifficultyPredictor
from adapters import get_adapter

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
XGB_CKPT    = ROOT / "weights" / "xgboost" / "predictor.pkl"
SPLITS_FILE = ROOT / "dataset" / "video_splits.json"
SCORES_BASE = ROOT / "scores" / "xgboost"

# UA-DETRAC/UAVDT: full-res MobileNetV3 FPN, conf_thr=0.5  (matches XGBoost training setup)
# MOT17: read the SAME full-res local XML detections as derived/ptc/routing.
# NOTE: the XGBoost predictor is trained on UA-DETRAC full-res features, so MOT17
# inference must also use full-res detections. The external
# FASTERRCNN-MOBILENET-V3-LARGE-320-FPN .txt is genuinely 320 low-res (≈1.75× more
# boxes, different conf distribution) and was a train/infer resolution mismatch.
MODEL_WEAK       = "FASTERRCNN-MOBILENET-V3-LARGE-FPN"
MODEL_STRONG     = "FASTERRCNN-RESNET50-FPN-V2"
CONF_THR       = 0.5
CONF_THR_MOT17 = 0.1
IOF_THR    = 0.5
IOU_MATCH  = 0.7            # TP IoU threshold for delta_tp target (matches metrics.match_detections_to_gt)
DERIVE_CONF_THR = 0.0       # feature/label derivation keeps all boxes
IMG_W, IMG_H = 1920, 1080   # used for density normalisation

# Local MOT17 XML detection files (generated by compute_mot17_detections.py at full res,
# same source consumed by compute_ptc.py / compute_derived.py / compute_mot17_routing.py)
import re as _re
import xml.etree.ElementTree as _ET
LOCAL_MOT17_XML_ROOT = ROOT / "data" / "mot17" / "pred_xml" / "TRAIN"
LOCAL_MOT17_WEAK     = "fasterrcnn_mobilenet_v3_large_320_fpn"  # folder label only; full-res model

# Dataset roots (download datasets into <repo>/data/; see detection/README.md).
DATA_ROOTS = {
    "ua-detrac": ROOT / "data" / "UA-DETRAC",
    "uavdt":     ROOT / "data" / "UAVDT",
    "mot17":     ROOT / "data" / "MOT17",
}

VEHICLE_IDS = {3, 4, 6, 8}   # COCO: car, motorcycle, bus, truck
PERSON_IDS  = {1}

_NAME_TO_ID = {
    "car": 3, "motorcycle": 4, "bus": 6, "truck": 8,
    "person": 1, "bicycle": 2, "van": 3, "vehicle": 3,
}


def _valid_ids(dataset: str):
    return PERSON_IDS if dataset == "mot17" else VEHICLE_IDS


def _parse_det_file(det_file: Path):
    """Return {frame_id: [(x,y,w,h,conf,cls_int,track_id), ...]}."""
    dets = {}
    if not det_file.exists():
        return dets
    with open(det_file) as f:
        for line in f:
            parts = line.strip().split(",")
            if len(parts) < 7:
                continue
            try:
                fid  = int(parts[0])
                x, y, w, h = float(parts[2]), float(parts[3]), float(parts[4]), float(parts[5])
                conf = float(parts[6])
                raw  = parts[7].strip() if len(parts) > 7 else "car"
                if raw.lstrip("-").isdigit():
                    cls = int(raw)
                else:
                    cls = _NAME_TO_ID.get(raw.lower())
                    if cls is None:
                        continue
            except (ValueError, IndexError):
                continue
            dets.setdefault(fid, []).append((x, y, w, h, conf, cls, 0))
    return dets


def _parse_mot17_xml_seq(seq: str):
    """Load MOT17 full-res detections from local XML (same source as compute_ptc.py).

    Returns {frame_id: [(x, y, w, h, conf, cls_int=1, track_id=0), ...]} in xywh,
    matching _parse_det_file's structure so score_video can consume it unchanged.
    """
    seq_dir = LOCAL_MOT17_XML_ROOT / LOCAL_MOT17_WEAK / seq
    dets = {}
    if not seq_dir.is_dir():
        return dets
    for xml_path in sorted(seq_dir.glob("*.xml")):
        try:
            fid = int(_re.sub(r"\D", "", xml_path.stem))
        except ValueError:
            continue
        frame = []
        try:
            root = _ET.parse(xml_path).getroot()
        except Exception:
            dets[fid] = frame
            continue
        for obj in root.findall(".//object"):
            try:
                conf_el = obj.find("confidence")
                conf = float(conf_el.text) if conf_el is not None and conf_el.text else 1.0
                box_el = obj.find("bndbox")
                if box_el is None:
                    continue
                xmin = float(box_el.findtext("xmin", "0"))
                ymin = float(box_el.findtext("ymin", "0"))
                xmax = float(box_el.findtext("xmax", "0"))
                ymax = float(box_el.findtext("ymax", "0"))
                if xmax <= xmin or ymax <= ymin:
                    continue
                frame.append((xmin, ymin, xmax - xmin, ymax - ymin, conf, 1, 0))  # cls 1 = person
            except Exception:
                continue
        dets[fid] = frame
    return dets


def _ignored_mask(dets_xywh: np.ndarray, ign_xywh: np.ndarray,
                  thr: float = IOF_THR) -> np.ndarray:
    """Vectorized IoF filter: returns boolean mask of dets whose IoF with ANY
    ignored region exceeds thr. Matches compute_ptc.py's scalar logic but
    O(D·I) in numpy instead of a Python triple loop (UAVDT has ~2000 regions).
    """
    if len(dets_xywh) == 0 or len(ign_xywh) == 0:
        return np.zeros(len(dets_xywh), dtype=bool)
    dx, dy, dw, dh = (dets_xywh[:, 0:1], dets_xywh[:, 1:2],
                      dets_xywh[:, 2:3], dets_xywh[:, 3:4])
    ix, iy, iw, ih = ign_xywh[:, 0], ign_xywh[:, 1], ign_xywh[:, 2], ign_xywh[:, 3]
    inter_w = np.clip(np.minimum(dx + dw, ix + iw) - np.maximum(dx, ix), 0, None)
    inter_h = np.clip(np.minimum(dy + dh, iy + ih) - np.maximum(dy, iy), 0, None)
    inter = inter_w * inter_h                       # (D, I)
    area = np.clip(dw * dh, 1e-9, None)             # (D, 1)
    iof = inter / area                              # (D, I)
    return (iof > thr).any(axis=1)


def _count_tp(dets_xywh, gt_objs, ignored_arr, iou_thr: float = IOU_MATCH) -> int:
    """Greedy IoU matching → TP count. Matches metrics.match_detections_to_gt:
    drop dets in ignored regions, greedy by descending conf, IoU>=thr one-to-one.
    gt_objs: list of {'bbox': (l,t,w,h)} (xywh). dets_xywh: (x,y,w,h,conf,...) tuples.
    """
    if not gt_objs:
        return 0
    dets = list(dets_xywh)
    if len(ignored_arr):
        cand = np.array([d[:4] for d in dets], dtype=np.float32) if dets else np.zeros((0, 4), np.float32)
        keep = ~_ignored_mask(cand, ignored_arr) if len(cand) else np.zeros(0, bool)
        dets = [d for d, k in zip(dets, keep) if k]
    dets = sorted(dets, key=lambda d: d[4], reverse=True)
    gt_boxes = [g["bbox"] for g in gt_objs]
    matched = [False] * len(gt_boxes)
    tp = 0
    for d in dets:
        best_iou, best_g = 0.0, -1
        for gi, gb in enumerate(gt_boxes):
            if matched[gi]:
                continue
            iou = _iou_xywh_pair(d[:4], gb)
            if iou > best_iou:
                best_iou, best_g = iou, gi
        if best_iou >= iou_thr and best_g >= 0:
            matched[best_g] = True
            tp += 1
    return tp


def _iou_xywh_pair(a, b) -> float:
    ax, ay, aw, ah = a; bx, by, bw, bh = b
    ix1 = max(ax, bx); iy1 = max(ay, by)
    ix2 = min(ax + aw, bx + bw); iy2 = min(ay + ah, by + bh)
    inter = max(0., ix2 - ix1) * max(0., iy2 - iy1)
    union = aw * ah + bw * bh - inter
    return inter / union if union > 0 else 0.


def derive_features_video(adapter, video: str, data_root: Path, out_path: Path,
                          valid_ids: set) -> bool:
    """Export per-frame 28-dim features + delta_tp target for XGBoost training.

    Feature derivation uses conf_threshold=0.0 (keep all boxes),
    ignored-region filtering, delta_tp = strong_tp - weak_tp at IoU>=0.7.
    Output columns match DifficultyPredictor.feature_columns + 'delta_tp'.
    """
    weak_file   = adapter.get_detection_file(MODEL_WEAK,   video, data_root)
    strong_file = adapter.get_detection_file(MODEL_STRONG, video, data_root)
    if not weak_file.exists() or not strong_file.exists():
        print(f"  [SKIP] {video}: missing weak/strong detection file")
        return False
    try:
        gt_data, ignored = adapter.load_gt(video, data_root)
    except Exception:
        print(f"  [SKIP] {video}: GT load failed")
        return False
    ign_arr = np.asarray(ignored, dtype=np.float32) if ignored else np.zeros((0, 4), np.float32)

    weak_raw   = _parse_det_file(weak_file)
    strong_raw = _parse_det_file(strong_file)
    frame_ids = sorted(set(weak_raw) | set(strong_raw) | set(gt_data))
    if not frame_ids:
        return False

    img_w, img_h = adapter.get_image_size(video, data_root)
    extractor = FrameFeatureExtractor(image_width=img_w, image_height=img_h)
    rows = []
    for fid in frame_ids:
        # weak dets: conf>=0 (keep all) + valid class, then ignored filter
        w_cand = [d for d in weak_raw.get(fid, [])
                  if d[4] >= DERIVE_CONF_THR and d[5] in valid_ids]
        if w_cand and len(ign_arr):
            cb = np.array([d[:4] for d in w_cand], dtype=np.float32)
            keep = ~_ignored_mask(cb, ign_arr)
            w_dets = [d for d, k in zip(w_cand, keep) if k]
        else:
            w_dets = w_cand
        s_dets = [d for d in strong_raw.get(fid, [])
                  if d[4] >= DERIVE_CONF_THR and d[5] in valid_ids]

        boxes  = np.array([[d[0], d[1], d[0]+d[2], d[1]+d[3]] for d in w_dets], dtype=np.float32) \
                 if w_dets else np.zeros((0, 4), dtype=np.float32)
        scores = np.array([d[4] for d in w_dets], dtype=np.float32)
        labels = np.array([d[5] for d in w_dets], dtype=np.int32)
        feat = extractor.update(boxes, scores, labels, valid_ids)

        gt_objs = gt_data.get(fid, [])
        weak_tp   = _count_tp(w_dets, gt_objs, ign_arr)
        strong_tp = _count_tp(s_dets, gt_objs, ign_arr)
        rows.append({"frame_id": fid, **feat, "delta_tp": strong_tp - weak_tp})

    pd.DataFrame(rows).to_csv(out_path, index=False, float_format="%.6f")
    print(f"  {video}: {len(rows)} frames  (mean delta_tp={np.mean([r['delta_tp'] for r in rows]):.3f})")
    return True


def score_video(predictor: DifficultyPredictor, adapter,
                video: str, data_root: Path,
                out_path: Path, window: int, valid_ids: set,
                model_weak: str = MODEL_WEAK,
                conf_thr: float = CONF_THR,
                dets_raw: dict = None,
                ignored: list = None) -> bool:
    if dets_raw is None:
        det_file = adapter.get_detection_file(model_weak, video, data_root)
        if not det_file.exists():
            print(f"  [SKIP] {video}: detection file missing")
            return False
        dets_raw = _parse_det_file(det_file)

    # Filter out detections in ignored regions (matches compute_ptc.py:
    # IoF>0.5 filtering before feature extraction).
    if ignored is None:
        try:
            _, ignored = adapter.load_gt(video, data_root)
        except Exception:
            ignored = []
    ign_arr = np.asarray(ignored, dtype=np.float32) if ignored else np.zeros((0, 4), np.float32)

    frame_ids = sorted(dets_raw)
    if not frame_ids:
        return False

    img_w, img_h = adapter.get_image_size(video, data_root)
    extractor = FrameFeatureExtractor(image_width=img_w, image_height=img_h)
    buf: deque = deque(maxlen=window)
    # Build all window feature vectors first, then run ONE batched predict.
    # Per-frame predict() is ~100× slower due to fixed XGBoost call overhead.
    X_rows: List[np.ndarray] = []
    X_frame_ids: List[int] = []
    rows = []

    for fid in frame_ids:
        cand = [d for d in dets_raw.get(fid, [])
                if d[4] >= conf_thr and d[5] in valid_ids]
        if cand and len(ign_arr):
            cand_xywh = np.array([d[:4] for d in cand], dtype=np.float32)
            keep = ~_ignored_mask(cand_xywh, ign_arr)
            frame_dets = [d for d, k in zip(cand, keep) if k]
        else:
            frame_dets = cand
        # detection files store ltwh; FrameFeatureExtractor expects xyxy
        boxes  = np.array([[d[0], d[1], d[0]+d[2], d[1]+d[3]] for d in frame_dets], dtype=np.float32) \
                 if frame_dets else np.zeros((0, 4), dtype=np.float32)
        scores = np.array([d[4] for d in frame_dets], dtype=np.float32)
        labels = np.array([d[5] for d in frame_dets], dtype=np.int32)

        feat = extractor.update(boxes, scores, labels, valid_ids)
        buf.append(feat)

        if len(buf) == window:
            X_rows.append(build_window_vector(list(buf), predictor.feature_columns)[0])
            X_frame_ids.append(fid)
        rows.append({"frame_id": fid, "predicted_gain": float("nan")})

    if X_rows:
        preds = predictor.predict(np.asarray(X_rows, dtype=np.float32))
        pred_by_fid = dict(zip(X_frame_ids, (float(p) for p in preds)))
        for r in rows:
            if r["frame_id"] in pred_by_fid:
                r["predicted_gain"] = pred_by_fid[r["frame_id"]]

    pd.DataFrame(rows).to_csv(out_path, index=False, float_format="%.6f")
    print(f"  {video}: {len(rows)} frames")
    return True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--datasets", nargs="+",
                        default=["ua-detrac", "uavdt", "mot17"],
                        choices=["ua-detrac", "uavdt", "mot17"])
    parser.add_argument("--split", choices=["train", "test", "both"], default="both")
    parser.add_argument("--window", type=int, default=7)
    parser.add_argument("--derive-only", action="store_true",
                        help="Export 28-dim features + delta_tp target for train_xgboost.py "
                             "(no predictor needed). Writes scores/derived/{weak}_vs_{strong}/.")
    args = parser.parse_args()

    with open(SPLITS_FILE) as f:
        splits = json.load(f)

    # ---- Derive-only: produce training features (features + delta_tp target) ----
    if args.derive_only:
        out_dir = ROOT / "scores" / "derived" / f"{MODEL_WEAK}_vs_{MODEL_STRONG}"
        out_dir.mkdir(parents=True, exist_ok=True)
        for ds in args.datasets:
            if ds == "mot17":
                print("[SKIP] mot17 derive-only (XGBoost trained on UA-DETRAC vehicle features)")
                continue
            adapter   = get_adapter(ds)
            data_root = DATA_ROOTS[ds]
            ds_splits = splits.get(ds, {})
            videos = []
            if args.split in ("train", "both"):
                videos += ds_splits.get("train", [])
            if args.split in ("test", "both"):
                videos += ds_splits.get("test", [])
            print(f"\nDerive features — {ds} ({len(videos)} videos) → {out_dir}")
            ok = sum(derive_features_video(adapter, v, data_root,
                                           out_dir / f"{v}.csv", _valid_ids(ds))
                     for v in videos)
            print(f"Done: {ok}/{len(videos)}")
        return

    if not XGB_CKPT.exists():
        sys.exit(f"Predictor not found: {XGB_CKPT}\nRun: python training/train_xgboost.py")

    predictor = DifficultyPredictor.load(str(XGB_CKPT))
    print(f"Loaded predictor from {XGB_CKPT}  (window={args.window})")

    for ds in args.datasets:
        adapter   = get_adapter(ds)
        data_root = DATA_ROOTS[ds]
        out_dir   = SCORES_BASE / ds
        out_dir.mkdir(parents=True, exist_ok=True)

        ds_splits = splits.get(ds, {})
        videos = []
        if args.split in ("train", "both"):
            videos += ds_splits.get("train", [])
        if args.split in ("test", "both"):
            videos += ds_splits.get("test", [])

        is_mot17 = (ds == "mot17")
        conf_thr = CONF_THR_MOT17 if is_mot17 else CONF_THR
        if is_mot17:
            print(f"\nXGBoost — {ds} ({len(videos)} videos, "
                  f"source=local full-res XML, conf_thr={conf_thr})")
            ok = sum(score_video(predictor, adapter, v, data_root,
                                 out_dir / f"{v}.csv", args.window,
                                 _valid_ids(ds), MODEL_WEAK, conf_thr,
                                 dets_raw=_parse_mot17_xml_seq(v), ignored=[])
                     for v in videos)
        else:
            print(f"\nXGBoost — {ds} ({len(videos)} videos, "
                  f"model={MODEL_WEAK}, conf_thr={conf_thr})")
            ok = sum(score_video(predictor, adapter, v, data_root,
                                 out_dir / f"{v}.csv", args.window,
                                 _valid_ids(ds), MODEL_WEAK, conf_thr)
                     for v in videos)
        print(f"Done: {ok}/{len(videos)}")


if __name__ == "__main__":
    main()
